/// Soft status badge: tinted background, coloured dot, readable dark text.
class SevChip extends StatelessWidget {
  const SevChip(this.category, {super.key, this.large = false, this.label, this.short = false});
  final String? category;
  final bool large;
  final bool short;
  final String? label;

  @override
  Widget build(BuildContext context) {
    final s = Sev.of(category);
    return Container(
      padding: EdgeInsets.symmetric(horizontal: large ? 12 : 9, vertical: large ? 6 : 3),
      decoration: BoxDecoration(color: s.tint, borderRadius: BorderRadius.circular(999)),
      child: Row(mainAxisSize: MainAxisSize.min, children: [
        Container(width: large ? 9 : 7, height: large ? 9 : 7, decoration: BoxDecoration(color: s.color, shape: BoxShape.circle)),
        SizedBox(width: large ? 8 : 6),
        Text(label ?? (short ? s.short : s.label),
            style: TextStyle(color: s.ink, fontWeight: FontWeight.w600, fontSize: large ? 14 : 12.5)),
      ]),
    );
  }
}

class StatusDot extends StatelessWidget {
  const StatusDot(this.status, {super.key, this.label, this.dark = false});
  final String status;
  final String? label;
  final bool dark;

  static Color colorFor(String s) => switch (s) {
        'ok' || 'online' || 'running' => HG.routine,
        'degraded' || 'paused' || 'simulated_outage' => HG.elevated,
        'fault' || 'error' || 'offline' => HG.high,
        'stale' => HG.unavailable,
        _ => Colors.grey,
      };

  @override
  Widget build(BuildContext context) => Row(mainAxisSize: MainAxisSize.min, children: [
        Container(width: 8, height: 8, decoration: BoxDecoration(color: colorFor(status), shape: BoxShape.circle)),
        const SizedBox(width: 8),
        Flexible(
          child: Text(label ?? status.replaceAll('_', ' '),
              overflow: TextOverflow.ellipsis,
              style: TextStyle(fontSize: 13, fontWeight: FontWeight.w500, color: dark ? Colors.white70 : HG.text)),
        ),
      ]);
}

