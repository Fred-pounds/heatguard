/// Primary content container.
class SectionCard extends StatelessWidget {
  const SectionCard({super.key, this.title, this.subtitle, this.trailing, required this.child, this.padding = const EdgeInsets.all(20)});
  final String? title;
  final String? subtitle;
  final Widget? trailing;
  final Widget child;
  final EdgeInsets padding;

  @override
  Widget build(BuildContext context) {
    final t = Theme.of(context).textTheme;
    return Card(
      child: Padding(
        padding: padding,
        child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, mainAxisSize: MainAxisSize.min, children: [
          if (title != null) ...[
            Row(crossAxisAlignment: CrossAxisAlignment.center, children: [
              Expanded(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Text(title!, style: t.titleMedium),
                  if (subtitle != null) Padding(padding: const EdgeInsets.only(top: 2), child: Text(subtitle!, style: t.bodySmall)),
                ]),
              ),
              ?trailing,
            ]),
            const SizedBox(height: 16),
          ],
          child,
        ]),
      ),
    );
  }
}

/// A single key number. Neutral by default; colour only when it signals status.
class StatCard extends StatelessWidget {
  const StatCard({super.key, required this.label, required this.value, this.icon, this.color, this.footnote, this.onTap});
  final String label;
  final String value;
  final IconData? icon;
  final Color? color;
  final String? footnote;
  final VoidCallback? onTap;

  @override
  Widget build(BuildContext context) {
    final t = Theme.of(context).textTheme;
    return Card(
      clipBehavior: Clip.antiAlias,
      child: InkWell(
        onTap: onTap,
        child: Padding(
          padding: const EdgeInsets.all(18),
          child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Row(children: [
              if (color != null) ...[
                Container(width: 8, height: 8, decoration: BoxDecoration(color: color, shape: BoxShape.circle)),
                const SizedBox(width: 8),
              ],
              Expanded(child: Text(label, style: t.labelMedium, maxLines: 1, overflow: TextOverflow.ellipsis)),
              if (icon != null) Icon(icon, size: 18, color: HG.muted),
            ]),
            const SizedBox(height: 8),
            // Values stay neutral; status colour is limited to the small dot.
            Text(value, style: const TextStyle(fontSize: 26, fontWeight: FontWeight.w700, color: HG.text, height: 1.1)),
            if (footnote != null) ...[
              const SizedBox(height: 4),
              Text(footnote!, style: t.bodySmall, maxLines: 1, overflow: TextOverflow.ellipsis),
            ],
          ]),
        ),
      ),
    );
  }
}

