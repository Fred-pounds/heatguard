class StatusDot extends StatelessWidget {
  const StatusDot(this.status, {super.key, this.label, this.dark = false});
  final String status;
  final String? label;
  final bool dark;

  static Color colorFor(String s) {
    switch (s) {
      case 'ok':
      case 'online':
      case 'running':
        return HG.routine;
      case 'degraded':
      case 'paused':
      case 'simulated_outage':
        return HG.elevated;
      case 'fault':
      case 'error':
      case 'offline':
        return HG.high;
      case 'stale':
        return HG.unavailable;
      default:
        return Colors.grey;
    }
  }

  @override
  Widget build(BuildContext context) {
    final c = colorFor(status);
    return Row(mainAxisSize: MainAxisSize.min, children: [
      Container(width: 9, height: 9, decoration: BoxDecoration(color: c, shape: BoxShape.circle)),
      const SizedBox(width: 6),
      Text(label ?? status.replaceAll('_', ' '),
          style: TextStyle(fontSize: 12, fontWeight: FontWeight.w600, color: dark ? Colors.white70 : HG.text)),
    ]);
  }
}

